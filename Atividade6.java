public class Atividade6 {
    public static void main(String[] args) {
        int atual = 0;
        for (int i = 1; i != 10; i++) {
            atual++;
            int anterior, soma;
            anterior = atual;
            soma = anterior + atual;
            System.out.println(soma);


        }
    }
}
